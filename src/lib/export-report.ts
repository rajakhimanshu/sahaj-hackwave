import { jsPDF } from "jspdf";
import type { DocumentAnalysis } from "./types";

export function buildReportText(analysis: DocumentAnalysis, fileName?: string) {
  const lines = [
    "SAHAJ DOCUMENT BRIEF",
    "====================",
    fileName ? `File: ${fileName}` : "",
    `Type: ${analysis.documentType}`,
    `Category: ${analysis.category}`,
    `Title: ${analysis.title}`,
    `Confidence: ${Math.round((analysis.confidence ?? 0) * 100)}%`,
    `Scam risk score: ${analysis.scamScore ?? 0}/100`,
    "",
    "SUMMARY (EN)",
    analysis.summarySimple,
    "",
    "SUMMARY (HI)",
    analysis.summaryHindi,
    "",
    "IF YOU IGNORE THIS",
    analysis.whatHappensIfIgnored || "—",
    "",
    "CATEGORY DESK",
    analysis.categoryFocus?.headline || "—",
    analysis.categoryFocus?.primaryAction
      ? `Primary action: ${analysis.categoryFocus.primaryAction}`
      : "",
    "",
    "ACTION CHECKLIST",
    ...(analysis.actionChecklist || []).map(
      (a, i) =>
        `${i + 1}. [${a.priority}] ${a.step}${a.deadline ? ` (by ${a.deadline})` : ""}`
    ),
    "",
    "AMOUNTS",
    ...(analysis.amounts || []).map((a) => `- ${a.label}: ${a.value}`),
    "",
    "DATES",
    ...(analysis.importantDates || []).map(
      (d) => `- ${d.label}: ${d.date} (${d.urgency})`
    ),
    "",
    "RISKS",
    ...(analysis.riskFlags || []).map((r) => `- [${r.level}] ${r.message}`),
    "",
    "FAMILY SHOULD KNOW",
    ...(analysis.familyWhoShouldKnow || []).map((f) => `- ${f}`),
    "",
    "RIGHTS & ESCALATION GUIDE",
    analysis.legalGuidance?.documentNature || "Not identified",
    ...(analysis.legalGuidance?.obligations || []).map(
      (item) => `- Obligation: ${item}`
    ),
    ...(analysis.legalGuidance?.rightsOrOptions || []).map(
      (item) => `- Option: ${item}`
    ),
    ...(analysis.legalGuidance?.escalationSteps || []).map(
      (item) => `- Escalation: ${item}`
    ),
    ...(analysis.legalGuidance?.officialHelp || []).map(
      (item) => `- Official help: ${item}`
    ),
    "Important: Sahaj explains documents; it does not provide legal advice.",
    "",
    "Generated by Sahaj · Powered by Google Gemini",
    "Privacy: prefer sharing only documents you are allowed to process.",
  ];
  return lines.filter((l) => l !== undefined && l !== "").join("\n");
}

function safeName(analysis: DocumentAnalysis) {
  return `sahaj-${(analysis.title || "brief").replace(/[^\w\-]+/g, "-").slice(0, 40)}`;
}

export function downloadReport(analysis: DocumentAnalysis, fileName?: string) {
  const blob = new Blob([buildReportText(analysis, fileName)], {
    type: "text/plain;charset=utf-8",
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${safeName(analysis)}.txt`;
  a.click();
  URL.revokeObjectURL(url);
}

export function downloadReportPdf(analysis: DocumentAnalysis, fileName?: string) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const margin = 48;
  const width = doc.internal.pageSize.getWidth() - margin * 2;
  let y = margin;

  const write = (text: string, opts?: { size?: number; bold?: boolean; gap?: number }) => {
    const size = opts?.size ?? 11;
    doc.setFont("helvetica", opts?.bold ? "bold" : "normal");
    doc.setFontSize(size);
    const lines = doc.splitTextToSize(text, width) as string[];
    for (const line of lines) {
      if (y > doc.internal.pageSize.getHeight() - margin) {
        doc.addPage();
        y = margin;
      }
      doc.text(line, margin, y);
      y += size + 4;
    }
    y += opts?.gap ?? 6;
  };

  doc.setFillColor(20, 46, 63);
  doc.rect(0, 0, doc.internal.pageSize.getWidth(), 64, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Sahaj document brief", margin, 38);
  y = 88;
  doc.setTextColor(22, 42, 53);

  write(analysis.title || analysis.documentType, { size: 16, bold: true, gap: 10 });
  write(
    [
      fileName ? `File: ${fileName}` : null,
      `Type: ${analysis.documentType}`,
      `Category: ${analysis.category}`,
      `Confidence: ${Math.round((analysis.confidence ?? 0) * 100)}%`,
      `Scam risk: ${analysis.scamScore ?? 0}/100`,
    ]
      .filter(Boolean)
      .join("  ·  "),
    { size: 10, gap: 14 }
  );

  write("Summary", { size: 13, bold: true, gap: 4 });
  write(analysis.summarySimple || "—", { gap: 10 });
  write("Hindi summary", { size: 13, bold: true, gap: 4 });
  write(analysis.summaryHindi || "—", { gap: 10 });

  if (analysis.categoryFocus?.headline) {
    write("Category desk", { size: 13, bold: true, gap: 4 });
    write(analysis.categoryFocus.headline, { bold: true, gap: 2 });
    if (analysis.categoryFocus.primaryAction) {
      write(`Primary action: ${analysis.categoryFocus.primaryAction}`, { gap: 8 });
    }
    for (const panel of analysis.categoryFocus.panels || []) {
      write(panel.title, { bold: true, gap: 2 });
      for (const item of panel.items) write(`• ${item}`, { size: 10, gap: 2 });
      y += 4;
    }
  }

  write("Action checklist", { size: 13, bold: true, gap: 4 });
  if (!analysis.actionChecklist?.length) write("No checklist items.", { gap: 8 });
  analysis.actionChecklist?.forEach((a, i) => {
    write(
      `${i + 1}. [${a.priority}] ${a.step}${a.deadline ? ` (by ${a.deadline})` : ""}`,
      { gap: 2 }
    );
  });
  y += 6;

  write("Amounts & dates", { size: 13, bold: true, gap: 4 });
  if (!analysis.amounts?.length && !analysis.importantDates?.length) {
    write("None clearly extracted.", { gap: 8 });
  }
  analysis.amounts?.forEach((a) => write(`• ${a.label}: ${a.value}`, { gap: 2 }));
  analysis.importantDates?.forEach((d) =>
    write(`• ${d.label}: ${d.date} (${d.urgency})`, { gap: 2 })
  );
  y += 6;

  if (analysis.legalGuidance) {
    write("Rights & escalation guide", { size: 13, bold: true, gap: 4 });
    write(analysis.legalGuidance.documentNature || "—", { gap: 4 });
    analysis.legalGuidance.obligations?.forEach((item) =>
      write(`Obligation: ${item}`, { gap: 2 })
    );
    analysis.legalGuidance.rightsOrOptions?.forEach((item) =>
      write(`Option: ${item}`, { gap: 2 })
    );
    analysis.legalGuidance.escalationSteps?.forEach((item) =>
      write(`Escalation: ${item}`, { gap: 2 })
    );
    analysis.legalGuidance.officialHelp?.forEach((item) =>
      write(`Official help: ${item}`, { gap: 2 })
    );
    y += 6;
  }

  write(
    "Important: Sahaj explains documents; it does not provide legal advice. Verify amounts and deadlines on the original paper or official portal before paying or signing.",
    { size: 9, gap: 8 }
  );
  write("Generated by Sahaj · Google Gemini · Device-local vault compatible", {
    size: 9,
    gap: 0,
  });

  doc.save(`${safeName(analysis)}.pdf`);
}

