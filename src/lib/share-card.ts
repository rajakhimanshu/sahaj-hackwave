import type { DocumentAnalysis } from "./types";
import { categoryLabel } from "./category-focus";

/** Keep WhatsApp text short and avoid dumping full ID payloads. */
export function buildFamilyShareText(analysis: DocumentAnalysis): string {
  const isId = analysis.category === "id_kyc";
  const title = isId
    ? "ID / KYC document — privacy checklist"
    : analysis.title || analysis.documentType;
  const summary = (analysis.summarySimple || "").slice(0, 280);
  const actions = (analysis.actionChecklist || [])
    .slice(0, 3)
    .map((a, i) => `${i + 1}. ${a.step}${a.deadline ? ` (by ${a.deadline})` : ""}`);
  const amounts = isId
    ? []
    : (analysis.amounts || [])
        .slice(0, 3)
        .map((a) => `• ${a.label}: ${a.value}`);
  const dates = (analysis.importantDates || [])
    .slice(0, 3)
    .map((d) => `• ${d.label}: ${d.date}`);

  const lines = [
    "📋 Sahaj family brief",
    `${categoryLabel(analysis.category)} · ${title}`,
    `Scam risk: ${analysis.scamScore ?? 0}/100`,
    "",
    summary,
    "",
    actions.length ? "Next steps:" : null,
    ...actions,
    amounts.length ? "" : null,
    amounts.length ? "Amounts:" : null,
    ...amounts,
    dates.length ? "" : null,
    dates.length ? "Dates:" : null,
    ...dates,
    "",
    isId
      ? "⚠️ Do not forward full ID photos on WhatsApp. Share this checklist only."
      : "Verify amounts on the original paper / official portal before paying.",
    "— Generated by Sahaj (explains docs, not legal advice)",
  ];

  return lines.filter((l) => l !== null && l !== undefined).join("\n");
}

export function whatsAppShareUrl(text: string) {
  return `https://wa.me/?text=${encodeURIComponent(text)}`;
}

export function openWhatsAppShare(analysis: DocumentAnalysis) {
  const url = whatsAppShareUrl(buildFamilyShareText(analysis));
  window.open(url, "_blank", "noopener,noreferrer");
}

export async function copyFamilyShareText(analysis: DocumentAnalysis) {
  const text = buildFamilyShareText(analysis);
  await navigator.clipboard.writeText(text);
  return text;
}

/** Draw a WhatsApp-ready PNG card (1080×1350). */
export function renderShareCardPng(analysis: DocumentAnalysis): Promise<Blob> {
  return new Promise((resolve, reject) => {
    const W = 1080;
    const H = 1350;
    const canvas = document.createElement("canvas");
    canvas.width = W;
    canvas.height = H;
    const ctx = canvas.getContext("2d");
    if (!ctx) {
      reject(new Error("Canvas unavailable"));
      return;
    }

    const isId = analysis.category === "id_kyc";
    const night = "#142e3f";
    const paper = "#f5f0e6";
    const accent = "#d95f3f";
    const glow = "#efb84f";
    const slate = "#5c6b73";

    // Background
    ctx.fillStyle = paper;
    ctx.fillRect(0, 0, W, H);

    // Top band
    ctx.fillStyle = night;
    ctx.fillRect(0, 0, W, 220);
    ctx.fillStyle = glow;
    ctx.fillRect(0, 220, W, 8);

    ctx.fillStyle = "#ffffff";
    ctx.font = "700 28px Georgia, serif";
    ctx.fillText("SAHAJ · FAMILY SHARE CARD", 64, 72);

    ctx.font = "600 22px system-ui, sans-serif";
    ctx.fillStyle = glow;
    ctx.fillText(categoryLabel(analysis.category).toUpperCase(), 64, 120);

    const title = isId
      ? "ID / KYC — share the checklist, not the photo"
      : (analysis.title || analysis.documentType).slice(0, 64);
    ctx.fillStyle = "#ffffff";
    ctx.font = "700 44px Georgia, serif";
    wrapText(ctx, title, 64, 170, W - 128, 48);

    // Scam badge
    const scam = analysis.scamScore ?? 0;
    ctx.fillStyle = scam >= 60 ? "#b42318" : scam >= 30 ? "#b54708" : "#067647";
    roundRect(ctx, 64, 260, 280, 56, 8);
    ctx.fill();
    ctx.fillStyle = "#ffffff";
    ctx.font = "700 24px system-ui, sans-serif";
    ctx.fillText(`Scam risk ${scam}/100`, 84, 296);

    // Summary
    let y = 360;
    ctx.fillStyle = night;
    ctx.font = "700 26px Georgia, serif";
    ctx.fillText("In plain words", 64, y);
    y += 44;
    ctx.fillStyle = slate;
    ctx.font = "400 28px system-ui, sans-serif";
    y = wrapText(
      ctx,
      (analysis.summarySimple || "—").slice(0, 320),
      64,
      y,
      W - 128,
      40
    );

    // Actions
    y += 48;
    ctx.fillStyle = night;
    ctx.font = "700 26px Georgia, serif";
    ctx.fillText("Do this next", 64, y);
    y += 40;
    const actions = (analysis.actionChecklist || []).slice(0, 3);
    ctx.font = "500 26px system-ui, sans-serif";
    for (const [i, a] of actions.entries()) {
      ctx.fillStyle = accent;
      ctx.fillText(`${i + 1}.`, 64, y);
      ctx.fillStyle = night;
      y = wrapText(ctx, a.step.slice(0, 90), 110, y, W - 174, 34);
      y += 18;
    }

    // Amounts / dates strip
    if (!isId) {
      const amounts = (analysis.amounts || []).slice(0, 2);
      if (amounts.length) {
        y += 20;
        ctx.fillStyle = night;
        ctx.font = "700 26px Georgia, serif";
        ctx.fillText("Money on the paper", 64, y);
        y += 40;
        ctx.font = "600 28px system-ui, sans-serif";
        for (const a of amounts) {
          ctx.fillStyle = slate;
          ctx.fillText(a.label.slice(0, 28), 64, y);
          ctx.fillStyle = night;
          ctx.fillText(a.value.slice(0, 24), 520, y);
          y += 40;
        }
      }
    }

    // Footer
    ctx.fillStyle = night;
    ctx.fillRect(0, H - 120, W, 120);
    ctx.fillStyle = glow;
    ctx.font = "600 22px system-ui, sans-serif";
    ctx.fillText("Verify on the original · Not legal advice", 64, H - 68);
    ctx.fillStyle = "rgba(255,255,255,0.7)";
    ctx.font = "400 20px system-ui, sans-serif";
    ctx.fillText("Powered by Sahaj · Google Gemini", 64, H - 36);

    canvas.toBlob((blob) => {
      if (!blob) reject(new Error("Could not build share image"));
      else resolve(blob);
    }, "image/png");
  });
}

export async function downloadShareCardPng(analysis: DocumentAnalysis) {
  const blob = await renderShareCardPng(analysis);
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `sahaj-share-${(analysis.title || "brief").replace(/[^\w\-]+/g, "-").slice(0, 32)}.png`;
  a.click();
  URL.revokeObjectURL(url);
}

function wrapText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  maxWidth: number,
  lineHeight: number
) {
  const words = text.split(/\s+/);
  let line = "";
  for (const word of words) {
    const test = line ? `${line} ${word}` : word;
    if (ctx.measureText(test).width > maxWidth && line) {
      ctx.fillText(line, x, y);
      line = word;
      y += lineHeight;
    } else {
      line = test;
    }
  }
  if (line) {
    ctx.fillText(line, x, y);
    y += lineHeight;
  }
  return y;
}

function roundRect(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number
) {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
}
